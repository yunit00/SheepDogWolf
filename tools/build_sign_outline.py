#!/usr/bin/env python3
"""Generate only mesh coordinates from the artwork alpha; never change the image."""
import math
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parents[1]
im = Image.open(root/'localization/ru/channel/sign.png')
a = im.getchannel('A'); w,h=im.size
points=[]
for i in range(96):
    angle = 2*math.pi*i/96
    dx,dy=math.cos(angle),math.sin(angle)
    last=None
    for radius in range(1,max(w,h)):
        x,y=round(w/2+radius*dx),round(h/2+radius*dy)
        if x<0 or y<0 or x>=w or y>=h: break
        if a.getpixel((x,y))>=160: last=(x,y)
    assert last
    points.append((last[0]/w*220-110,220-last[1]/h*147))
out=root/'src/objects/channel_sign_outline.h'
out.write_text('// Generated by tools/build_sign_outline.py from channel/sign.png alpha.\n'
    'static const float kChannelOutline[][2] = {\n'+''.join(f'    {{{x:.3f}f, {y:.3f}f}},\n' for x,y in points)+'};\n')
print(out)
